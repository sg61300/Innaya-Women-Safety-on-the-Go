// Generates assets/illustrations/illustrations.generated.ts from the .webp files
// actually present in assets/illustrations/. Metro's require() needs static
// string literals and a real file, so the map only ever references files that
// exist — a missing key falls back to the emblem in <Illustration/>. Re-run this
// whenever illustration files are added or removed:
//   node scripts/illustrations-map.mjs
import { readdirSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "..", "assets", "illustrations");
if (!existsSync(dir)) mkdirSync(dir, { recursive: true });

const files = readdirSync(dir)
  .filter((f) => f.toLowerCase().endsWith(".webp"))
  .sort();

const entries = files
  .map((f) => `  ${JSON.stringify(f.replace(/\.webp$/i, ""))}: require(${JSON.stringify("./" + f)}),`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/illustrations-map.mjs — do not edit by hand.
// Re-run \`node scripts/illustrations-map.mjs\` after adding or removing .webp files.
import type { ImageSourcePropType } from "react-native";

// Only files present at generation time are listed; <Illustration/> falls back to
// the emblem for any key without a file here.
export const ILLUSTRATION_FILES: Record<string, ImageSourcePropType> = {
${entries}
};
`;

writeFileSync(join(dir, "illustrations.generated.ts"), out);
console.log(`illustrations map: ${files.length} file(s)` + (files.length ? `\n - ${files.join("\n - ")}` : ""));
